const Guide = {
  ft: 0, fn: 0,
  // what an item is used for, collected from every system that takes it
  uses(id) {
    const it = ITEMS[id]; if (!it) return '';
    const base = it.base || id, out = [];
    if (it.sell) out.push(`ขายได้ ~${baht(priceOf(id))}`);
    if (it.en) out.push(`กินได้ +${it.en}⚡`);
    const rec = Object.keys(RECIPES).filter(k => RECIPES[k].need[base]);
    if (rec.length) out.push('ทำอาหาร: ' + rec.map(k => RECIPES[k].i + RECIPES[k].n).join(', '));
    if (typeof MACHINES !== 'undefined') {
      const m = [];
      if (FRUIT.includes(base)) m.push('🫙 แยม', '🧃 น้ำผลไม้หมัก'); else if (VEG.includes(base)) m.push('🥒 ผักดอง');
      if (base === 'milk') m.push('🧀 ชีส'); if (base === 'wool') m.push('🧶 ผ้าทอมือ');
      if (m.length) out.push('แปรรูปด้วยเครื่องจักร: ' + m.join(', '));
      const cr = CRAFTS.filter(c => c.need[base]).map(c => ITEMS[c.id].i + ITEMS[c.id].n);
      for (const k in MACHINES) if (MACHINES[k].cost[base]) cr.push(MACHINES[k].i + MACHINES[k].n);
      if (cr.length) out.push('ใช้สร้าง: ' + cr.join(', '));
    }
    if (it.cat === 'seed') { const C = CROPS[it.seed]; out.push(C.tree ? 'ปลูกในสวนผลไม้หลังบ้าน' : `ปลูกในแปลงผัก โต ${C.grow} ชม.`); }
    if (it.cat === 'tool' && TOOLS[id] && TOOLS[id].desc) out.push(TOOLS[id].desc);
    if (typeof SOCIAL_ITEMS !== 'undefined' && SOCIAL_ITEMS[id]) out.push(SOCIAL_ITEMS[id]);
    if (it.cat === 'crop' || it.cat === 'product' || it.cat === 'dish' || it.cat === 'artisan') out.push('ใช้ส่งออเดอร์ ให้ของขวัญชาวบ้าน หรือบริจาคโครงการ');
    if (it.cat === 'mineral' || it.cat === 'fish') out.push('เก็บลงสมุดสะสม');
    return out.join(' · ');
  },
  open(tab) {
    UI.open('คู่มือระบบทั้งหมด', ['ระบบในเกม', 'ของในกระเป๋า'], t => {
      if (t === 0) return `<p class="lead">แต่ละระบบใช้ทำอะไร และมีไว้ทำไม</p><div class="grid">${SYSTEMS.map(s => `<div class="card"><div class="ci">${s.i}</div><div class="cb"><h4>${s.n}</h4><p><b>ทำอะไร:</b> ${s.what}</p><p class="dim"><b>มีไว้ทำไม:</b> ${s.why}</p></div></div>`).join('')}</div>`;
      const ids = Object.keys(S.inv).filter(id => ITEMS[id] && S.inv[id] > 0);
      if (!ids.length) return '<p class="empty">กระเป๋ายังว่าง</p>';
      return `<div class="grid">${ids.map(id => `<div class="card"><div class="ci">${ITEMS[id].i}</div><div class="cb"><h4>${esc(ITEMS[id].n)} <small>×${S.inv[id]}</small></h4><p class="dim">${this.uses(id)}</p></div></div>`).join('')}</div>`;
    }, { tab: tab || 0, wide: true });
  },
  fps(dt) {
    this.ft += dt; this.fn++;
    if (this.ft < 0.5) return;
    const f = Math.round(this.fn / this.ft); this.ft = 0; this.fn = 0;
    const el = document.getElementById('fps'); if (!el) return;
    el.style.display = S && S.showFps !== false ? '' : 'none';
    el.textContent = f + ' FPS'; el.className = f >= 50 ? 'ok' : f >= 30 ? 'mid' : 'bad';
  },
};
UI.H.guide = d => Guide.open(+d.v || 0);
UI.H.fps = () => { S.showFps = S.showFps === false; };
